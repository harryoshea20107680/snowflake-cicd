CREATE OR REPLACE PROCEDURE SP_ADD_TRANSACTION(
    P_CUSTOMER_NAME VARCHAR,
    P_AMOUNT NUMBER(10,2),
    P_STATUS VARCHAR
)
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
BEGIN

    INSERT INTO TRANSACTIONS_T (
        CUSTOMER_NAME,
        AMOUNT,
        TRANSACTION_STATUS
    )
    VALUES (
        :P_CUSTOMER_NAME,
        :P_AMOUNT,
        :P_STATUS
    );

    RETURN 'Transaction inserted successfully';

END;
$$;
