create or replace view TRANSACTION_SUMMARY_V(
	TRANSACTION_STATUS,
	TRANSACTION_COUNT,
	TOTAL_AMOUNT,
	AVERAGE_AMOUNT
) as
SELECT
    TRANSACTION_STATUS,
    COUNT(*) AS TRANSACTION_COUNT,
    SUM(AMOUNT) AS TOTAL_AMOUNT,
    AVG(AMOUNT) AS AVERAGE_AMOUNT
FROM TRANSACTIONS_T
GROUP BY TRANSACTION_STATUS;
